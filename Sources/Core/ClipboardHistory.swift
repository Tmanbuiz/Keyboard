import Foundation

/// Android-style clipboard history rules, kept free of UIKit so they can be unit tested.
/// Items are stored newest first. Pinned items never expire and are not removed by the recent-item cap.
public enum ClipboardHistory {
    public static let maxRecent = 40
    public static let maxPinned = 60
    public static let maxLength = 5000
    public static let dayOptions = [1, 7, 30]

    /// Pasteboard types that password managers and other apps use to mark sensitive or temporary content.
    public static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.apple.is-sensitive"
    ]

    public static func shouldCapture(_ text: String, types: [String] = []) -> Bool {
        guard !types.contains(where: sensitiveTypes.contains) else { return false }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.isEmpty && text.count <= 20_000
    }

    /// Adds `text` as the newest item. A duplicate moves to the top and keeps its pin.
    public static func adding(_ text: String, to items: [SavedPhrase], pinned: Bool = false,
                              now: Date = Date(), keepDays: Int? = nil) -> [SavedPhrase] {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return items }
        let stored = String(text.prefix(maxLength))
        var list = items
        var item = SavedPhrase(text: stored, pinned: pinned, createdAt: now)
        if let index = list.firstIndex(where: { $0.text == stored }) {
            item.id = list[index].id
            item.pinned = list[index].pinned || pinned
            list.remove(at: index)
        }
        list.insert(item, at: 0)
        return pruned(list, now: now, keepDays: keepDays)
    }

    /// Removes expired recent items and enforces the size caps, keeping the newest.
    public static func pruned(_ items: [SavedPhrase], now: Date = Date(), keepDays: Int? = nil) -> [SavedPhrase] {
        let cutoff = keepDays.map { now.addingTimeInterval(-Double(max($0, 1)) * 86_400) }
        var recent = 0, pinned = 0
        return items.filter { item in
            if item.pinned { pinned += 1; return pinned <= maxPinned }
            if let cutoff, item.createdAt < cutoff { return false }
            recent += 1
            return recent <= maxRecent
        }
    }

    /// Display order: pinned first, then newest first.
    public static func ordered(_ items: [SavedPhrase]) -> [SavedPhrase] {
        items.sorted { $0.pinned == $1.pinned ? $0.createdAt > $1.createdAt : $0.pinned && !$1.pinned }
    }

    /// A one-line preview for the suggestion bar.
    public static func preview(_ text: String, length: Int = 24) -> String {
        let line = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
        let compact = line.trimmingCharacters(in: .whitespaces)
        return compact.count > length ? String(compact.prefix(length)) + "…" : compact
    }
}
